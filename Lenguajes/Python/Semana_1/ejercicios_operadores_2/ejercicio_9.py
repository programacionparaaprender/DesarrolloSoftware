# Un negocio tiene como meta vender 100 productos esta semana. Hasta ahora ha vendido 65 productos. Calcula cuántos productos faltan para alcanzar la meta restando lo ya vendido al total objetivo.
# Solución
meta = 100
vendidos = 65

faltan = meta - vendidos

print(f"Faltan {faltan} productos para alcanzar la meta.")