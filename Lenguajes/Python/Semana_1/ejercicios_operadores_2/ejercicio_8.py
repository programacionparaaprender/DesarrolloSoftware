# La temperatura en Ciudad A es de 28 grados y en Ciudad B es de 22 grados. Calcula cuántos grados más de temperatura tiene Ciudad A comparado con Ciudad B, haciendo una resta entre ambas temperaturas.
# Solución
temperatura_ciudad_a = 28
temperatura_ciudad_b = 22

diferencia = temperatura_ciudad_a - temperatura_ciudad_b

print(f"Ciudad A tiene {diferencia} grados más que Ciudad B.")