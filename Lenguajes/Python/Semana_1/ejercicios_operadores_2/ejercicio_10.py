# Se vendieron tres productos con ingresos de 150, 200 y 100 soles respectivamente. Calcula el ingreso promedio por producto sumando los tres ingresos y dividiendo entre la cantidad de productos.
# Solución
ingreso_producto_1 = 150
ingreso_producto_2 = 200
ingreso_producto_3 = 100

suma_ingresos = ingreso_producto_1 + ingreso_producto_2 + ingreso_producto_3
cantidad_productos = 3

promedio_ingreso = suma_ingresos / cantidad_productos

print(f"El ingreso promedio por producto es: {promedio_ingreso:.2f} soles")