# Un médico atendió pacientes durante cinco días de la semana. El lunes atendió a 8, el martes a 10, el miércoles a 12, el jueves a 7 y el viernes a 9. Calcula el total de pacientes que atendió durante la semana sumando todos los días.
# Solución
lunes = 8
martes = 10
miercoles = 12
jueves = 7
viernes = 9

total_pacientes = lunes + martes + miercoles + jueves + viernes

print(f"El total de pacientes atendidos en la semana es: {total_pacientes}")