# Calcula el volumen de una esfera con un radio de 5 cm utilizando la fórmula V = (4/3) * π * r^3, donde "r" representa el radio de la esfera. El resultado es 523.5987755982989.
# Solución
import math

radio = 5
volumen = (4 / 3) * math.pi * (radio ** 3)
print(f"El volumen de la esfera es de : {volumen}")