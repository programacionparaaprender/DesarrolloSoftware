# Calcula el área de un triángulo dado su base y altura. Utilice la fórmula A = (b * h) / 2, donde A es el área, b es la base con valor 5 y h es la altura con valor 9 del triángulo. El resultado es 22.5
# Solución
base = 5
height = 9

area = (base * height) / 2
print(f"El área es : {area}") # El área es : 22.5