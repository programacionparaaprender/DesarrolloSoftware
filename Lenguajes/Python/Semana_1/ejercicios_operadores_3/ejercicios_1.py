# Calcula el promedio los siguientes números value_1=20, value_2=18, value_3=15 , value_4=12. Para hacer esto, primero sume todos los números y luego divida la suma total por el número de números existentes. El resultado es 16.25.
# Solución
value_1 = 20
value_2 = 18
value_3 = 15
value_4 = 12

total_sum = value_1 + value_2 + value_3 + value_4
number_of_numbers = 4
average = total_sum / number_of_numbers

print(f"El promedio es : {average}")