# Calcula el volumen de un cono con una base circular de radio de 5 cm y una altura de 10 cm utilizando la fórmula V = (1/3) * π * r^2 * h. El resultado es 261.79938779914943.
# Solución
import math

radio = 5
altura = 10

volumen = (1 / 3) * math.pi * (radio ** 2) * altura
print(f"El volumen del cono es de {volumen}")